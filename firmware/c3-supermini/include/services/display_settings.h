#pragma once

#include <cstddef>

namespace services::settings {

constexpr size_t kOtaPasswordMaxLen = 32;
/** Shortest settings password the portal accepts. */
constexpr size_t kOtaPasswordMinLen = 8;
constexpr int kTextScaleMinPercent = 80;
constexpr int kTextScaleMaxPercent = 130;
constexpr int kTextScaleDefaultPercent = 110;
/** Longest accepted NTP host name or IPv4 address (one DNS label limit). */
constexpr size_t kNtpServerMaxLen = 63;

/** Load persistent display and OTA settings from NVS. */
void init();

bool footerEnabled();
bool weatherEnabled();
bool temperatureFahrenheit();
bool use24HourClock();
int textScalePercent();
const char* otaPassword();

/** Length of generated settings passwords (5 bits per character: 50 bits). */
constexpr size_t kGeneratedPasswordLen = 10;
/** Writes len random characters and a NUL to out. */
using PasswordGenerator = void (*)(char* out, size_t len);
/** Call before init(); init() uses it when no password is set. */
void setPasswordGenerator(PasswordGenerator generator);
/** A generated password that nobody has used yet: show it on the screen. */
bool otaPasswordNeedsShowing();
/** The password was generated by the device (not set by the user). */
bool otaPasswordGenerated();
/** The user has seen or used the password; stop showing it. */
void markOtaPasswordShown();
/** Primary NTP server (host name or IPv4 address). */
const char* ntpServer();

/**
 * Validate and store the NTP server from the portal. Empty restores the
 * default; an invalid value is ignored. Returns true when the stored server
 * changed (the caller should restart time sync).
 */
bool saveNtpServerFromPortal(const char* value);

/** True for host names / IPv4 addresses: letters, digits, '.', '-' only. */
bool isValidNtpServer(const char* value);

/** Longest accepted POSIX TZ string. */
constexpr size_t kTimeZoneMaxLen = 63;

/**
 * POSIX TZ rule for the footer clock, e.g. "GMT0BST,M3.5.0/1,M10.5.0".
 * Empty means automatic: the UTC offset reported by Open-Meteo for the radar
 * location.
 */
const char* timeZone();

/**
 * Validate and store the time zone from the portal. Empty selects automatic;
 * an invalid value is ignored. Returns true when the stored value changed.
 */
bool saveTimeZoneFromPortal(const char* value);

/** True for a well-formed POSIX TZ string (empty is not valid here). */
bool isValidTimeZone(const char* value);

enum class PasswordChange { kUnchanged, kChanged, kTooShort };

/**
 * Store web-portal values. An empty password keeps the current password so
 * the portal never needs to echo the stored secret into its HTML; one
 * shorter than kOtaPasswordMinLen is ignored (the rest is still saved).
 */
PasswordChange saveFromPortal(const char* footer_checkbox, const char* weather_checkbox,
                    const char* fahrenheit_checkbox,
                    const char* clock24_checkbox,
                    const char* text_scale_percent_value,
                    const char* ota_password_value);

// --- Aircraft filter and route lookups ---

/** Highest accepted altitude limit (ft). */
constexpr int kAltitudeLimitMaxFt = 60000;

/** Show aircraft reporting "ground" (taxiing / parked). */
bool showGroundAircraft();
/** Lowest altitude shown (ft); 0 = no minimum. */
int minAltitudeFt();
/** Highest altitude shown (ft); 0 = no maximum. */
int maxAltitudeFt();
/**
 * True when an airborne aircraft at alt_ft passes the altitude limits.
 * Ground aircraft are governed by showGroundAircraft() alone.
 */
bool altitudeAllowed(float alt_ft);
/** Look up routes and aircraft types on ADSBDB (sends callsigns to it). */
bool routeLookupsEnabled();

/**
 * Parse an altitude limit from the portal: blank = 0 (no limit); digits with
 * optional spaces/commas ("10,000"); 0..kAltitudeLimitMaxFt. False if invalid.
 */
bool parseAltitudeLimit(const char* value, int* out_ft);

/**
 * Store the aircraft filter from the portal. Invalid altitude limits (bad
 * number, or minimum above maximum) keep the previous limits.
 */
void saveAircraftFilterFromPortal(const char* ground_checkbox,
                                  const char* min_alt_value,
                                  const char* max_alt_value,
                                  const char* lookups_checkbox);

// --- Device name (mDNS / DHCP host name) ---

/** Longest accepted device name (one DNS label, kept short for mDNS). */
constexpr size_t kDeviceNameMaxLen = 32;

/** Host name, e.g. "plane-radar" -> http://plane-radar.local */
const char* deviceName();

/** a-z, 0-9 and '-', not starting or ending with '-' (lower case only). */
bool isValidDeviceName(const char* value);

/**
 * Validate and store the device name (lower-cased; blank restores the
 * default; invalid is ignored). Returns true when it changed: the caller
 * should restart so mDNS and DHCP use the new name.
 */
bool saveDeviceNameFromPortal(const char* value);

// --- Radar view extras ---

/** Compass bearing at the top of the screen (0 = north up), 0..359. */
int upBearingDeg();
/** Show the airline name (from ADSBDB) as a fourth tag line. */
bool showAirlineNames();
/** Draw light aircraft smaller/yellow and military aircraft in their colour. */
bool aircraftClassColors();
/** Turn the screen off between nightOffFromHour() and nightOffToHour(). */
bool nightOffEnabled();
/** Local hour (0..23) the screen turns off. */
int nightOffFromHour();
/** Local hour (0..23) the screen turns back on. */
int nightOffToHour();
/**
 * True when local_hour is inside the off period. The period may wrap past
 * midnight (e.g. 23 -> 7); from == to means never.
 */
bool hourInNightOff(int local_hour);

/**
 * Parse a whole number in [min_value, max_value]; blank gives blank_value.
 * Surrounding spaces are allowed. False if invalid.
 */
bool parseIntSetting(const char* value, int min_value, int max_value,
                     int blank_value, int* out);

/** Store the view extras from the portal; invalid numbers keep old values. */
void saveViewFromPortal(const char* up_bearing_value,
                        const char* airline_checkbox,
                        const char* class_colors_checkbox,
                        const char* night_checkbox, const char* night_from_value,
                        const char* night_to_value);

// --- Medium airports (downloaded per area) ---

bool showMediumAirports();
void saveMediumAirportsFromPortal(const char* checkbox);

// --- Aircraft tags ---

/** Move or shorten tags so they don't overlap (upstream #9). Default on. */
bool avoidTagOverlap();
void saveTagOverlapFromPortal(const char* checkbox);

// --- Local ADS-B receiver (readsb / tar1090 / dump1090-fa) ---

/** Longest stored receiver URL. */
constexpr size_t kReceiverUrlMaxLen = 120;

/** Fetch aircraft from the local receiver instead of adsb.fi. */
bool receiverEnabled();
/** Full aircraft.json URL (http://...); empty when not set. */
const char* receiverUrl();
/** Use adsb.fi while the receiver can't be reached. */
bool receiverFallback();

/**
 * Tidies a receiver address typed into Setup: adds "http://" when there is
 * no scheme and "/data/aircraft.json" when there is no path, so
 * "192.168.1.50:8080" works. Only http:// and https:// are accepted; no
 * spaces or quotes. False when invalid or too long (empty input gives an
 * empty out and true).
 */
bool normaliseReceiverUrl(const char* in, char* out, size_t out_len);

/**
 * Stores the receiver settings. An invalid URL keeps the previous one and
 * returns false; the checkboxes are saved either way.
 */
bool saveReceiverFromPortal(const char* enabled_checkbox, const char* url,
                            const char* fallback_checkbox);

/** Restore defaults during a full BOOT-button reset. */
void clear();

}  // namespace services::settings
